// src/pages/admin/ReportCategoryPage.tsx
import { useEffect, useState } from 'react';
import { Link, useParams } from 'react-router-dom';
import { ArrowLeft, Download, FileText, MoreVertical } from 'lucide-react';
import { fetchAdminReports, type AdminReport } from '../../services/adminReports';
import { describeError } from '../../services/api';
import './ReportCategoryPage.css';

const CATEGORY_LABELS: Record<string, string> = {
  usage: 'Usage reports',
  quality: 'Quality reports',
  verification: 'Verification reports',
  financial: 'Financial reports',
  institution: 'Institution reports',
};

const CATEGORY_HINTS: Record<string, string> = {
  usage: 'Users, sessions and platform activity',
  quality: 'Session quality and interpreter performance',
  verification: 'Credentials, approvals and pending verification',
  financial: 'Payments, wallet and transaction summaries',
  institution: 'Activity across organisations',
};

export function ReportCategoryPage() {
  const { category } = useParams<{ category: string }>();
  const [reports, setReports] = useState<AdminReport[] | null>(null);
  const [error, setError] = useState('');

  const label = category ? (CATEGORY_LABELS[category] ?? 'Reports') : 'Reports';
  const hint = category ? (CATEGORY_HINTS[category] ?? '') : '';

  useEffect(() => {
    let cancelled = false;
    fetchAdminReports(category)
      .then((list) => {
        if (!cancelled) setReports(list);
      })
      .catch((err) => {
        if (!cancelled) {
          setError(describeError(err));
          setReports([]);
        }
      });
    return () => {
      cancelled = true;
    };
  }, [category]);

  const loading = reports === null;
  const isEmpty = !loading && reports.length === 0;

  return (
    <div className="rc-page">
      <header className="rc-header">
        <Link to="/dashboard/admin/reports" className="rc-back">
          <ArrowLeft size={16} />
          Back to Reports
        </Link>
        <h1>{label}</h1>
        {hint && <p>{hint}</p>}
      </header>

      <section className="rc-panel">
        <header className="rc-panel__head">
          <h2>{label}</h2>
          <span className="rc-panel__count">
            {reports?.length ?? 0} report{(reports?.length ?? 0) === 1 ? '' : 's'}
          </span>
        </header>

        <div className="rc-table">
          <div className="rc-table__head">
            <span>REPORT NAME</span>
            <span>GENERATED</span>
            <span>GENERATED BY</span>
            <span>STATUS</span>
            <span>ACTION</span>
          </div>

          {loading ? (
            <p className="rc-empty">Loading reports…</p>
          ) : isEmpty ? (
            <p className="rc-empty">
              {error ? `Could not load reports: ${error}` : `No ${label.toLowerCase()} yet.`}
            </p>
          ) : (
            reports.map((r) => (
              <div className="rc-table__row" key={r.id}>
                <span className="rc-table__name">
                  <FileText size={14} />
                  <span>{r.name}</span>
                </span>
                <span className="rc-table__muted">{r.generatedAt}</span>
                <span className="rc-table__muted">{r.generatedBy}</span>
                <span className={`rc-badge rc-badge--${r.status}`}>
                  <i /> {r.status}
                </span>
                <span className="rc-table__actions">
                  <button type="button" className="rc-icon-btn" aria-label="Download">
                    <Download size={14} />
                  </button>
                  <button type="button" className="rc-icon-btn" aria-label="More">
                    <MoreVertical size={14} />
                  </button>
                </span>
              </div>
            ))
          )}
        </div>
      </section>
    </div>
  );
}
